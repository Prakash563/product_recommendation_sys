def recommend_similar_products(product_id, n=5):
    """Return the n products most similar to product_id."""
    if product_id not in product_to_idx:
        return pd.DataFrame(columns=["productid", "similarity_score"])

    product_index = product_to_idx[product_id]
    distances, indices = item_model.kneighbors(
        item_user_matrix[product_index],
        n_neighbors=min(n + 1, len(product_ids)),
    )
    indices = indices.flatten()
    scores = 1 - distances.flatten()

    keep = indices != product_index  # drop the query product itself
    indices, scores = indices[keep][:n], scores[keep][:n]

    return pd.DataFrame({"productid": product_ids[indices], "similarity_score": scores})


