def filter_min_ratings(data, min_user_ratings, min_product_ratings, max_rounds=5):
    """Iteratively drop users/products below the rating thresholds.

    Iteration is needed because removing sparse products can push a user
    below the threshold (and vice versa). It is capped at `max_rounds`
    because running to full convergence keeps shrinking the data with
    rapidly diminishing returns.
    """
    d = data.copy()
    for i in range(1, max_rounds + 1):
        user_counts = d["userid"].value_counts()
        product_counts = d["productid"].value_counts()
        keep_users = user_counts[user_counts >= min_user_ratings].index
        keep_products = product_counts[product_counts >= min_product_ratings].index

        before = len(d)
        d = d[d["userid"].isin(keep_users) & d["productid"].isin(keep_products)]
        print(f"  round {i}: {before:,} -> {len(d):,} ratings | "
              f"{d['userid'].nunique():,} users | {d['productid'].nunique():,} products")
        if len(d) == before:
            print("  converged")
            break
    return d.reset_index(drop=True)


