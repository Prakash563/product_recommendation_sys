def build_sparse_matrix(data):
    """CSR user x product ratings matrix plus id <-> index lookups."""
    user_ids = data["userid"].unique()
    product_ids = data["productid"].unique()
    user_to_idx = {u: i for i, u in enumerate(user_ids)}
    product_to_idx = {p: i for i, p in enumerate(product_ids)}

    rows = data["userid"].map(user_to_idx).to_numpy()
    cols = data["productid"].map(product_to_idx).to_numpy()
    matrix = csr_matrix(
        (data["ratings"].to_numpy(), (rows, cols)),
        shape=(len(user_ids), len(product_ids)),
    )
    return matrix, user_to_idx, product_to_idx, user_ids, product_ids


