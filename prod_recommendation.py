def build_cluster_top_products(data, user_cluster_map, top_n=TOP_N_PER_CLUSTER):
    """Top products per user cluster, ranked by mean rating * log(1 + count)."""
    d = data.assign(cluster=data["userid"].map(user_cluster_map))
    stats = d.groupby(["cluster", "productid"])["ratings"].agg(["mean", "count"]).reset_index()
    stats["score"] = stats["mean"] * np.log1p(stats["count"])
    return {
        int(cluster): group.nlargest(top_n, "score")["productid"].tolist()
        for cluster, group in stats.groupby("cluster")
    }


def build_global_top_products(data, top_n=TOP_N_PER_CLUSTER):
    """Global fallback list for cold-start users, same scoring as above."""
    stats = data.groupby("productid")["ratings"].agg(["mean", "count"]).reset_index()
    stats["score"] = stats["mean"] * np.log1p(stats["count"])
    return stats.nlargest(top_n, "score")["productid"].tolist()


